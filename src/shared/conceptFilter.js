/** 概念名规范化：去 "概念/板块" 后缀（东财"光刻胶概念" vs 同花顺"光刻胶" 归一同一个名字） */
export function normalizeConceptName(name) {
  return String(name ?? "").trim().replace(/(概念|板块)$/, "");
}

/** 是否广泛概念（一票否决判定，单独导出供统计/调试）
 *  v9.91.1：精确名单（用户复核 361 概念产物）优先，正则兜底防新增概念漏网 */
export function isBroadConcept(name) {
  if (!name) return false;
  const n = String(name).trim();
  if (!n) return false;
  const norm = normalizeConceptName(n);
  if (WIDE_CONCEPT_NAMES.includes(norm)) return true;
  return WIDE_PATTERNS.some(p => p.test(n));
}

/**
 * 全站唯一概念判定。
 * @param {string} name 板块/概念名
 * @param {Set<string>|null} whitelist 同花顺白名单（规范化后的概念名集合）；null=未加载
 * @returns {boolean} 是否真实题材概念（产品/行业级）
 */
export function isThemeBoardName(name, whitelist) {
  if (!name) return false;
  const n = String(name).trim();
  if (!n) return false;
  // ① 广泛概念一票否决（"一带一路/长三角/央国企改革"即使有词根/白名单也拦）
  if (isBroadConcept(n)) return false;
  // ② 同花顺白名单命中（规范化匹配："光刻胶概念" 命中 "光刻胶"）
  if (whitelist && whitelist.size > 0) {
    if (whitelist.has(normalizeConceptName(n))) return true;
    // ③ 词根兜底（东财概念名与同花顺不同，如"装配建筑"不在同花顺列表但词根命中）
    return THEME_HINTS.test(n);
  }
  // ④ 白名单未加载 → 旧兜底逻辑（渐进降级）
  return THEME_HINTS.test(n) || (!NON_THEME_PATTERNS.some(p => p.test(n)) && n.length <= 8);
}
