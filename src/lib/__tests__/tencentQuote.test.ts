import { describe, it, expect } from "vitest";
import { parseTencentQuote } from "../api";

const SAMPLE = `v_sh600519="1~贵州茅台~600519~1343.00~1346.50~1346.50~35060~17643~17416~1343.00~66~1342.99~5~1342.98~1~1342.97~1~1342.95~1~1343.03~1~1343.32~23~1344.20~1~1344.30~1~1344.40~5~~20260812161432~-3.50~-0.26~1356.88~1332.51~1343.00/35060/4717613108~35060~471761~0.28~20.30~~1356.88~1332.51~1.81~16788.60~16788.60~7.21~1481.15~1211.85~0.96~43~1345.60~15.41~20.39~~~0.19~471761.3108~13.4300~1~   A~GP-A~-0.46~2.80~3.87~30.53~26.78~1539.98~1151.01~1.67~7.35~3.60~1250081601~1250081601~40.95~-4.39~1250081601~~~-3.04~-0.01~~CNY~0~___D__F__N~1345.77~-14~";`;
const SAMPLE2 = `v_sz000001="51~平安银行~000001~11.25~11.26~11.26~865432~420001~445431~11.25~100~11.24~50~11.23~30~11.22~10~11.21~5~11.26~80~11.27~40~11.28~20~11.29~10~~20260812161432~-0.01~-0.09~11.35~11.18~11.25/865432/973610000~865432~97361~0.87~7.50~~11.35~11.18~1.51~2050.00~2050.00~0.65~6.35~6.35~0.55~55~11.26~2.30~2.05~~~0.11~97361.0000~1.1200~1~   A~GP-A~-0.55~3.20~4.10~28.50~24.80~1250.00~900.00~1.20~6.80~3.10~1250081601~1250081601~38.50~-3.20~1250081601~~~-2.80~-0.02~~CNY~0~___D__F__N~11.28~-50~";`;

describe("v9.109.2 parseTencentQuote（Q-2 腾讯实时报价）", () => {
  it("实测样例字段映射：名称/现价/涨跌幅/成交额(万元→元)/换手率", () => {
    const map = parseTencentQuote(SAMPLE);
    expect(map.size).toBe(1);
    const b = map.get("600519")!;
    expect(b.name).toBe("贵州茅台");
    expect(b.price).toBe(1343.0);
    expect(b.pct).toBeCloseTo(-0.26);
    expect(b.amount).toBeCloseTo(471761 * 1e4); // 471761 万元 → 元
    expect(b.turnoverRate).toBeCloseTo(0.28);
  });

  it("多只批量解析", () => {
    const map = parseTencentQuote(SAMPLE + SAMPLE2);
    expect(map.size).toBe(2);
    expect(map.get("000001")!.name).toBe("平安银行");
    expect(map.get("000001")!.price).toBe(11.25);
  });

  it("坏行/空文本 → 空 Map（不抛错）", () => {
    expect(parseTencentQuote("").size).toBe(0);
    expect(parseTencentQuote("v_xxx=bad").size).toBe(0);
  });
});
